def draw(top, rows, glyph_set):
    pen = TTGlyphPen(glyph_set)
    for r, line in enumerate(rows):
        y0 = (8 - (top + r)) * PX
        x = 0
        while x < len(line):
            if line[x] != '#':
                x += 1
                continue
            start = x
            while x < len(line) and line[x] == '#':
                x += 1
            # clockwise rectangle (TrueType outer contour), same as the original glyphs
            x0, x1, y1 = start * PX, x * PX, y0 + PX
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0))
            pen.closePath()
    return pen.glyph()


def main(src, dst):
    font = TTFont(src)
    cmap = font.getBestCmap()
    glyf, hmtx = font['glyf'], font['hmtx']
    order = font.getGlyphOrder()
    new_cmap = {}

    for ch, (top, rows) in GLYPHS.items():
        width = max(len(r) for r in rows)
        assert all(len(r) == width for r in rows), ch
        assert top + len(rows) <= 11, ch
        name = 'uni%04X' % ord(ch)
        glyph = draw(top, rows, font.getGlyphSet())
        glyph.recalcBounds(glyf)
        glyf[name] = glyph  # also appends the name to the glyph order
        hmtx[name] = ((width + 1) * PX, glyph.xMin)
        new_cmap[ord(ch)] = name

    for ch, latin in ALIASES.items():
        new_cmap[ord(ch)] = cmap[ord(latin)]

    expected = set(range(0x410, 0x450)) | {0x401, 0x451}
    assert set(new_cmap) == expected, sorted(expected ^ set(new_cmap))

    font.setGlyphOrder(order)
    font['maxp'].numGlyphs = len(order)
    for table in font['cmap'].tables:
        if table.isUnicode():
            table.cmap.update(new_cmap)
    os2 = font['OS/2']
    os2.ulUnicodeRange1 |= 1 << 9   # Cyrillic
    os2.ulCodePageRange1 |= 1 << 2  # cp1251
    os2.usLastCharIndex = max(os2.usLastCharIndex, 0x451)
    font.save(dst)
    print('added', len(GLYPHS), 'glyphs,', len(new_cmap), 'codepoints ->', dst)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
