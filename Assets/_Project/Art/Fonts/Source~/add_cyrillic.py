# Adds Cyrillic (U+0401, U+0410-U+044F, U+0451) to Gravewire-Regular.ttf.
# Usage: python add_cyrillic.py <in.ttf> <out.ttf>
# Grid: 1 px = 100 units, row 0 = top (y 800..900), row 8 = baseline row, rows 9-10 = descender.
